"""Write js/plan-data.js from the B.A.A. Level One plan (tools/plan_source.py).

Run: python tools/build_plan_data.py
"""
import json, sys, datetime as dt
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from plan_source import W, MI, conv

WEEK1 = dt.date(2026, 10, 26)  # Monday of plan week 1
RACE = dt.date(2027, 3, 14)
DAYS = ["Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]

sessions = []
for w, (phase, ss) in W.items():
    monday = WEEK1 + dt.timedelta(weeks=w - 1)
    for i, (kind, lo, hi, extra, title, detail) in enumerate(ss, start=1):
        date = monday + dt.timedelta(days=i)
        if date == RACE:
            kind, lo, hi, extra, title, detail = "race", 26.2188, 26.2188, 0, "Rome Marathon", "Race day. Goal 3:50:00 at 5:27/km."
        if kind == "q" and lo == 4 and extra:
            title = f"≈ {lo*MI+extra:.1f}–{hi*MI+extra:.1f} km hills"
        sessions.append({
            "week": w, "phase": phase, "date": date.isoformat(), "type": kind,
            "kmMin": round(lo * MI + extra, 1), "kmMax": round(hi * MI + extra, 1),
            "title": conv(title).replace("26.2188", "42.2"), "detail": conv(detail),
        })

out = Path(__file__).parent.parent / "js" / "plan-data.js"
out.write_text("// Generated by tools/build_plan_data.py. Do not edit by hand.\n"
               f"export const PLAN_START = '{WEEK1}';\nexport const RACE_DATE = '{RACE}';\n"
               f"export const SESSIONS = {json.dumps(sessions, ensure_ascii=False, indent=1)};\n", encoding="utf-8")
print(len(sessions), "sessions ->", out)
